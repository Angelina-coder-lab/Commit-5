package ru.payroll;

/**
 * Общий интерфейс элемента расчёта (начисление или удержание).
 * Новый вид начисления/удержания добавляется реализацией этого интерфейса
 * без правки уже написанных классов (принцип открытости-закрытости).
 */
public interface PayrollElement {

    /**
     * Код элемента (для идентификации в листке).
     */
    String code();

    /**
     * Человекочитаемое название.
     */
    String title();

    /**
     * Вид: начисление или удержание.
     */
    ElementKind kind();

    /**
     * Рассчитывает сумму в копейках для контекста расчёта.
     * Для начислений — положительная сумма к выплате.
     * Для удержаний — положительная сумма к удержанию (знак вычитает сервис).
     *
     * @param ctx контекст расчёта (сотрудник, период, уже посчитанная база и т.д.)
     * @return сумма в копейках (≥ 0)
     */
    long calculate(PayrollContext ctx);

    /**
     * Входит ли сумма в налоговую базу.
     * По умолчанию: все начисления — да, удержания — нет.
     * Конкретные начисления (например больничный) могут переопределить.
     */
    default boolean includedInTaxBase() {
        return kind() == ElementKind.ACCRUAL;
    }
}
